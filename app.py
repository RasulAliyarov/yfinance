with st.expander("📘 Шпаргалка инвестора: качество + тайминг"):
    st.markdown(
        """
### 1. Фундаментал — что мы покупаем?
- **Выручка и прибыль (⬆️)** — если растут, продукт нужен рынку.
- **Маржа (> 20%)** — бронежилет: позволяет выживать в инфляцию и давить конкурентов.
- **FCF (свободный кэш)** — если положительный, компания сама оплачивает свой банкет,
  а не живёт в долг и не размывает акционеров допэмиссиями.
- **Долг / капитализация (< 20–30%)** — запас прочности на случай кризиса.

### 2. Оценка — не переплачиваем ли?
- **P/E и P/FCF** — стоп-краны. Даже лучший бизнес становится плохой инвестицией по любой цене.
  Норма 15–25, перегрев > 40–50.
- **Капитализация** — «малышам» ($2–10B) проще вырасти в 5 раз, чем гигантам-триллионникам.

### 3. Техника — когда именно входим?
- **Нет новых минимумов (3–5 дней)** — главный фильтр. Пока каждый день ниже предыдущего — руки в карманах.
- **RSI (выход из ямы)** — паника (перепроданность) сменяется первыми покупками.
- **Объём (затухание)** — цена замирает, объёмы падают: слабые руки уже вышли.
- **Нижние тени свечей (откуп)** — следы крупных игроков, которые защищают уровень.

### 4. Перспектива — устойчиво ли это дальше?
Прошлое (выручка, прибыль, FCF) описывает то, что **уже случилось**. Отдельный блок
смотрит вперёд: прогноз роста прибыли и выручки на год, **пересмотр оценок аналитиками**
(повышают их или режут — главный сигнал), сдвиг консенсуса за 90 дней, PEG
(дорого ли стоит ожидаемый рост), forward P/E против trailing.

### Как читать вердикт
- **⛔️ ЗАПРЕТ** — цена делает новые минимумы, вход запрещён независимо от качества бизнеса.
- **⚠️ УСТОЙЧИВОСТЬ ПОД ВОПРОСОМ** — прошлое хорошее, но аналитики режут прогнозы / ждут спад.
- **⏳ ЖДЁМ ТЕХНИКУ** — бизнес хороший и перспектива в порядке, но точка входа ещё не созрела.
- **🟢 ЧАСТИЧНЫЙ ВХОД** — можно заходить частью позиции.
- **🚀 ПОЛНЫЙ ВХОД** — прошлое отличное, перспектива подтверждает, техника подтверждает.
- **❌ МИМО** — слабый бизнес, не тратим время.

> Отрицательный P/E — компания убыточна. Отрицательный P/FCF — прожигает наличность
> и может объявить допэмиссию, чтобы выжить.
"""
    )

